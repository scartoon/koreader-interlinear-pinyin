-- Character and word tables (pure Lua, no KOReader dependencies).
--
-- data/chars.tsv  char <TAB> rank <TAB> default reading
--                 rank 0 = not in the frequency list (very rare).
--                 Characters ranked 1..1000 are absent: no setting ever annotates them.
-- data/words.tsv  word <TAB> space-separated reading of each syllable
--                 <TAB> frequency (per billion words; optional, 0 if missing)
--                 Only words that contain an annotatable polyphonic character.
-- data/rules.tsv  char <TAB> L or R <TAB> neighbouring character <TAB> reading <TAB> examples
--                 Context rules: the reading of char when the character
--                 immediately to its left (L) or right (R) is the neighbour.
-- data/uncertain.tsv  char <TAB> confidence in the default (0-1) <TAB> most likely
--                 reading <TAB> second most likely reading
--                 Polyphonic characters whose default reading is not reliable
--                 when neither a word nor a rule decides.
--
-- chars.tsv and words.tsv are generated by tools/build_data.py, rules.tsv and
-- uncertain.tsv by tools/learn_from_cpp.py. Only chars.tsv is required.

local Data = {}
Data.__index = Data

-- One loaded copy per KOReader session, shared by every book.
local loaded = {}

local function read_lines(path, fn)
    local f = io.open(path, "r")
    if not f then return false end
    for line in f:lines() do fn(line) end
    f:close()
    return true
end

function Data.load(dir)
    if loaded[dir] then return loaded[dir] end
    local self = setmetatable({ chars = {}, words = {}, word_freq = {}, rules = {}, uncertain = {},
                                max_word_len = 1 }, Data)
    local chars, words, word_freq = self.chars, self.words, self.word_freq
    local ok_chars = read_lines(dir .. "/chars.tsv", function(line)
        local ch, rank, reading = line:match("^([^\t]+)\t(%d+)\t([^\t\r]+)")
        if ch then chars[ch] = { tonumber(rank), reading } end
    end)
    if not ok_chars then return nil, "missing " .. dir .. "/chars.tsv" end
    read_lines(dir .. "/words.tsv", function(line)
        local word, readings, freq = line:match("^([^\t]+)\t([^\t\r]+)\t?(%d*)")
        if word then
            local syllables = {}
            -- Split on the space character only: %S depends on the C locale,
            -- and in some (e.g. macOS UTF-8) byte 0xA0 counts as a space,
            -- which would cut "à" (C3 A0) in half.
            for syl in readings:gmatch("[^ ]+") do syllables[#syllables + 1] = syl end
            words[word] = syllables
            local f = tonumber(freq)
            if f and f > 0 then word_freq[word] = f end
            if #syllables > self.max_word_len then self.max_word_len = #syllables end
        end
    end)
    local rules = self.rules
    read_lines(dir .. "/rules.tsv", function(line)
        local ch, side, neighbour, reading, n = line:match("^([^\t]+)\t([LR])\t([^\t]+)\t([^\t\r]+)\t?(%d*)")
        if ch then
            rules[ch] = rules[ch] or {}
            rules[ch][side .. neighbour] = { reading, tonumber(n) or 0 }
        end
    end)
    local uncertain = self.uncertain
    read_lines(dir .. "/uncertain.tsv", function(line)
        local ch, confidence, first, second = line:match("^([^\t]+)\t([%d.]+)\t([^\t]+)\t([^\t\r]+)")
        if ch then uncertain[ch] = { tonumber(confidence), first, second } end
    end)
    loaded[dir] = self
    return self
end

-- rank (0 = unranked), default reading; or nil for common/unknown characters.
function Data:char(ch)
    local entry = self.chars[ch]
    if not entry then return nil end
    return entry[1], entry[2]
end

-- Reading from a context rule for ch with the given neighbours (either may be
-- nil), or nil. When both sides have a rule and they disagree, the one learned
-- from more examples wins.
function Data:rule(ch, left, right)
    local rules = self.rules[ch]
    if not rules then return nil end
    local l = left and rules["L" .. left]
    local r = right and rules["R" .. right]
    if l and r and l[1] ~= r[1] then
        return (r[2] > l[2]) and r[1] or l[1]
    end
    return (l or r) and (l or r)[1] or nil
end

-- The two most likely readings of an uncertain character (most likely first)
-- and the confidence in its default, or nil when the default is reliable.
function Data:uncertainty(ch)
    local entry = self.uncertain[ch]
    if not entry then return nil end
    return entry[2], entry[3], entry[1]
end

-- Syllable list for a multi-character word and its frequency (per billion
-- words, 0 when unknown), or nil.
function Data:word(word)
    local syllables = self.words[word]
    if not syllables then return nil end
    return syllables, self.word_freq[word] or 0
end

return Data
